#!/usr/bin/env python3
"""Imports the content review (words40.json) into the game:
  words.js          window.SK_WORDS = {five, pink, green} for data.js
  img/<key>.jpg     the chosen photo, 240x240 on white (bundled: the tablet is offline and only
                    reaches allowed hosts, so the hotlink URL is kept in the credits, not loaded)
  img/credits.json  word → title, author, licence, Commons page, hotlink URL
Then run make-audio.py. Usage (from games/skaitymas): python3 -I .tools/import-words.py <words40.json>"""
import io, json, os, re, shutil, sys, time, html, urllib.request, urllib.error
from PIL import Image

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UA = {"User-Agent": "skaitymas-content/1.0 (kids reading game)"}

def key(s):
    return "".join(c if ord(c) < 128 else "u%04x" % ord(c) for c in s)

def get(url):
    last = None
    for attempt in range(5):
        time.sleep(0.8)
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=30) as r:
                return r.read()
        except urllib.error.HTTPError as e:
            last = e
            time.sleep(min(int(e.headers.get("Retry-After") or 0) or 10 * (attempt + 1), 60))
        except Exception as e:
            last = e
            time.sleep(3)
    raise last

def plain(s):
    return html.unescape(re.sub(r"<[^>]+>", "", s or "")).strip()[:140]

words = json.load(open(sys.argv[1]))
five = [w["word"] for w in words if "five" in w["groups"]]
pink = [w["word"] for w in words if "pink" in w["groups"]]
green = [[w["word"], w["phonogram"]] for w in words if "green" in w["groups"] and w.get("phonogram")]
bad = [w for w in five if len(w) != 5]
if bad:
    sys.exit(f"not five letters: {bad}")
with open(os.path.join(HERE, "words.js"), "w") as f:
    f.write("/* Generated by .tools/import-words.py from the content review. Do not edit by hand. */\n")
    f.write("(typeof window !== 'undefined' ? window : globalThis).SK_WORDS = " + json.dumps({"five": five, "pink": pink, "green": green}, ensure_ascii=False, indent=1) + ";\n")

out = os.path.join(HERE, "img")
shutil.rmtree(out, ignore_errors=True)
os.makedirs(out)
credits = {}
for w in words:
    im = Image.open(io.BytesIO(get(w["image"]["thumb_url"]))).convert("RGB")
    im.thumbnail((240, 240), Image.LANCZOS)
    sq = Image.new("RGB", (240, 240), "white")
    sq.paste(im, ((240 - im.width) // 2, (240 - im.height) // 2))
    sq.save(os.path.join(out, key(w["word"]) + ".jpg"), "JPEG", quality=72, optimize=True, progressive=True)
    i = w["image"]
    credits[w["word"]] = {"file": key(w["word"]) + ".jpg", "title": i.get("title"), "artist": plain(i.get("artist")),
                          "license": plain(i.get("license")), "page": i.get("page_url"), "hotlink": i.get("thumb_url")}
    print(w["word"], "ok", flush=True)
json.dump(credits, open(os.path.join(out, "credits.json"), "w"), ensure_ascii=False, indent=1)
print(f"{len(five)} five-letter, {len(pink)} pink, {len(green)} green; {len(credits)} photos")
