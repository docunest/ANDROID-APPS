#!/usr/bin/env python3
"""Makes the single-level games from Skaitymas (owner 2026-11-25: Rašyk, Skaityk, Dėliok as their own
tiles, so the Ponas X closes only that game). Copies the shared files and writes only.js, meta.json and
icon.png per game. Run after any change to Skaitymas: python3 -I .tools/make-games.py (from games/skaitymas)."""
import json, os, shutil
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAMES = os.path.dirname(HERE)
SHARED = ["game.js", "data.js", "content.js", "words.js", "audio", "img"]
LIST = {
    "rasyk":   {"title": "Rašyk",   "color": "#AED581", "order": 112},
    "skaityk": {"title": "Skaityk", "color": "#90CAF9", "order": 114},
    "deliok":  {"title": "Dėliok",  "color": "#FFCC80", "order": 116},
}
version = json.load(open(os.path.join(HERE, "meta.json")))["version"]

def font(sz):
    for f in ("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", "/usr/share/fonts/dejavu/DejaVuSans-Bold.ttf"):
        if os.path.exists(f): return ImageFont.truetype(f, sz)
    return ImageFont.load_default()

def icon(gid, path):
    S = 1024; im = Image.new("RGBA", (S, S), (0, 0, 0, 0)); d = ImageDraw.Draw(im)
    if gid == "rasyk":   # a big pencil
        d.polygon([(220, 760), (300, 840), (840, 300), (760, 220)], fill=(255, 193, 7, 255))
        d.polygon([(760, 220), (840, 300), (900, 240), (820, 160)], fill=(239, 83, 80, 255))
        d.polygon([(220, 760), (300, 840), (170, 890)], fill=(255, 224, 178, 255))
        d.polygon([(170, 890), (205, 878), (183, 856)], fill=(55, 71, 79, 255))
    elif gid == "skaityk":   # an open book with a picture on one page
        d.polygon([(110, 260), (500, 320), (500, 830), (110, 770)], fill=(255, 255, 255, 255), outline=(55, 71, 79, 255), width=18)
        d.polygon([(914, 260), (524, 320), (524, 830), (914, 770)], fill=(255, 255, 255, 255), outline=(55, 71, 79, 255), width=18)
        d.ellipse((620, 420, 820, 620), fill=(255, 179, 0, 255))
        for y in (420, 500, 580, 660): d.line((180, y, 430, y + 30), fill=(120, 144, 156, 255), width=22)
    else:   # three letter blocks
        f = font(230)
        for i, (x, ch, c) in enumerate([(90, "d", (198, 40, 40)), (380, "ė", (21, 101, 192)), (670, "l", (198, 40, 40))]):
            y = 300 + (60 if i == 1 else 0)
            d.rounded_rectangle((x, y, x + 270, y + 300), 40, fill=(255, 255, 255, 255), outline=(55, 71, 79, 255), width=16)
            d.text((x + 135, y + 150), ch, font=f, fill=c + (255,), anchor="mm")
    im.resize((256, 256), Image.LANCZOS).save(path)

for gid, m in LIST.items():
    dst = os.path.join(GAMES, gid)
    os.makedirs(dst, exist_ok=True)
    for f in SHARED:
        src, out = os.path.join(HERE, f), os.path.join(dst, f)
        if os.path.isdir(out): shutil.rmtree(out)
        (shutil.copytree if os.path.isdir(src) else shutil.copyfile)(src, out)
    html = open(os.path.join(HERE, "index.html")).read()
    html = html.replace("<title>Skaitymas</title>", f"<title>{m['title']}</title>")
    html = html.replace('<script src="game.js"></script>', '<script src="only.js"></script>\n<script src="game.js"></script>')
    open(os.path.join(dst, "index.html"), "w").write(html)
    open(os.path.join(dst, "only.js"), "w").write(f"/* Generated by skaitymas/.tools/make-games.py: this game runs one level only. */\nwindow.SK_ONLY = '{gid}';\n")
    json.dump({"title": m["title"], "icon": "icon.png", "color": m["color"], "order": m["order"], "group": "learning",
               "version": version, "enabled": True, "network": ["map-pal-mike-base.vercel.app"]},
              open(os.path.join(dst, "meta.json"), "w"), ensure_ascii=False, indent=2)
    icon(gid, os.path.join(dst, "icon.png"))
    print(gid, "ok")
