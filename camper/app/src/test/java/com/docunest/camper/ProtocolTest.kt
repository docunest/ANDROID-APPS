package com.docunest.camper

import com.docunest.camper.midea.AcFrames
import com.docunest.camper.midea.AcState
import com.docunest.camper.midea.MideaCrypto.hex
import com.docunest.camper.midea.MideaDiscovery
import com.docunest.camper.midea.MideaPacket
import com.docunest.camper.midea.MideaV3
import com.docunest.camper.tuya.TuyaDiscovery
import com.docunest.camper.tuya.TuyaFrame
import org.json.JSONObject
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Test

/** Byte-for-byte checks against vectors generated by tinytuya / msmart-ng (scan/make_*_vectors.py in the laptop repo). */
class ProtocolTest {
    private fun res(name: String) = JSONObject(javaClass.classLoader!!.getResource(name).readText())
    private fun ByteArray.hexs() = joinToString("") { "%02x".format(it) }

    // ---------- Tuya 3.5 ----------

    @Test fun tuyaPack() {
        val v = res("tuya_vectors.json")
        val key = v.getString("key").toByteArray()
        val iv = v.getString("iv").toByteArray()
        val arr = v.getJSONArray("pack")
        for (i in 0 until arr.length()) {
            val p = arr.getJSONObject(i)
            val frame = TuyaFrame.pack(key, p.getInt("seq"), p.getInt("cmd"), hex(p.getString("payload")), iv)
            assertEquals(p.getString("frame"), frame.hexs())
        }
    }

    @Test fun tuyaUnpack() {
        val v = res("tuya_vectors.json")
        val key = v.getString("key").toByteArray()
        val arr = v.getJSONArray("unpack")
        for (i in 0 until arr.length()) {
            val p = arr.getJSONObject(i)
            val bytes = hex(p.getString("frame"))
            val (f, used) = TuyaFrame.unpack(bytes, 0, bytes.size, key)!!
            assertEquals(bytes.size, used)
            assertEquals(p.getInt("cmd"), f.cmd)
            assertEquals(p.getInt("seq"), f.seq)
            assertEquals(p.getString("payload"), f.text())
        }
    }

    @Test fun tuyaPartialFrameWaits() {
        val v = res("tuya_vectors.json")
        val bytes = hex(v.getJSONArray("unpack").getJSONObject(0).getString("frame"))
        assertEquals(null, TuyaFrame.unpack(bytes, 0, bytes.size - 3, v.getString("key").toByteArray()))
    }

    @Test fun tuyaSessionKey() {
        val s = res("tuya_vectors.json").getJSONObject("session")
        val key = res("tuya_vectors.json").getString("key").toByteArray()
        assertEquals(s.getString("key"), TuyaFrame.sessionKey(key, hex(s.getString("local_nonce")), hex(s.getString("remote_nonce"))).hexs())
    }

    @Test fun tuyaDiscovery() {
        val v = res("tuya_vectors.json")
        val u = v.getJSONObject("udp")
        val j = TuyaDiscovery.decode(hex(u.getString("packet")))
        assertNotNull(j)
        assertEquals(u.getJSONObject("json").getString("gwId"), j!!.getString("gwId"))
        // our request decodes with the same public key
        val req = TuyaDiscovery.decode(hex(v.getString("discovery_request")))
        assertEquals("app", req!!.getString("from"))
    }

    // ---------- Midea V3 ----------

    @Test fun mideaFrames() {
        val v = res("midea_vectors.json")
        assertEquals(v.getString("get_state"), AcFrames.getState(1).hexs())
        val s = v.getJSONObject("set_state")
        val st = AcState(power = true, target = 24.0, mode = 3, fan = 102, targetHumidity = 0)
        assertEquals(s.getString("frame"), AcFrames.setState(st, 5).hexs())
    }

    @Test fun mideaPacket() {
        val p = res("midea_vectors.json").getJSONObject("packet")
        val ts = byteArrayOf(12, 34, 56, 7, 1, 11, 26, 20)
        val pkt = MideaPacket.encode(p.getLong("device_id"), hex(p.getString("frame")), ts)
        assertEquals(p.getString("packet"), pkt.hexs())
        assertEquals(p.getString("frame"), MideaPacket.decode(pkt).hexs())
        assertEquals(p.getLong("device_id") and 0xFFFFFFFFFFFFL, MideaDiscovery.idOf(pkt))
    }

    @Test fun midea8370() {
        val v = res("midea_vectors.json").getJSONObject("v3")
        val key = hex(v.getString("local_key"))
        val enc = MideaV3.encodeRequest(key, v.getInt("packet_id"), hex(v.getString("data")), ByteArray(16) { 0xAB.toByte() })
        assertEquals(v.getString("encrypted"), enc.hexs())
        assertArrayEquals(hex(v.getString("data")), MideaV3.decode(key, hex(v.getString("response"))))
    }

    @Test fun mideaHandshake() {
        val h = res("midea_vectors.json").getJSONObject("handshake")
        assertEquals(h.getString("local_key"), MideaV3.localKey(hex(h.getString("key")), hex(h.getString("data"))).hexs())
    }

    @Test fun mideaRealState() {
        val s = res("midea_vectors.json").getJSONObject("state")
        val st = AcFrames.parseState(hex(s.getString("frame")))!!
        assertEquals(s.getBoolean("power"), st.power)
        assertEquals(s.getDouble("target"), st.target, 0.01)
        assertEquals(s.getInt("mode"), st.mode)
        assertEquals(s.getInt("fan"), st.fan)
        assertEquals(s.getDouble("indoor"), st.indoor!!, 0.01)
        assertEquals(null, st.outdoor)
        assertEquals(s.getBoolean("filter_alert"), st.filterAlert)
        assertEquals(s.getBoolean("display_on"), st.displayOn)
        assertEquals(s.getInt("error_code"), st.errorCode)
    }
}
